using HsSqlAgent.Server.Models;
using HsSqlAgent.SqlCore;
using SqlAgent.Service.Core.Execution;

namespace HsSqlAgent.Server.Tools;

internal enum McpErrorSurface
{
    Query,
    Metadata,
    Dml
}

/// <summary>
/// The MCP client is an untrusted error sink. Provider exception messages may
/// contain connection data, SQL text, identifiers and parameter values. Keep
/// the raw exception in restricted Audit/diagnostics, not client responses.
/// </summary>
internal static class McpErrorResponsePolicy
{
    internal const string SafeDmlUnknownOutcomeMessage =
        "Target transaction outcome is unconfirmed. Do not retry the mutation; " +
        "reconcile database state using the approval request ID.";

    internal static McpToolError ForDmlOutcomeUnknown(string code) =>
        code == "dml.rollback_outcome_unknown"
            ? new McpToolError(code, SafeDmlUnknownOutcomeMessage, "Rollback", false)
            : new McpToolError("dml.commit_outcome_unknown",
                SafeDmlUnknownOutcomeMessage, "Commit", false);

    internal static McpToolError ForDmlFlowFailure(
        string? code, string? stage, bool retryable)
    {
        // Error codes are generated by the typed approval flow, not by the
        // provider. Still constrain the string so a future caller cannot
        // accidentally put arbitrary driver text in a machine-readable field.
        var safeCode = IsSafeCode(code) ? code! : "dml.execution_failed";
        var safeStage = stage is "Approval" or "Preview" or "Commit" or "Rollback"
            or "Execution" or "Policy" or "Configuration" or "Capability"
            ? stage : "Execution";
        return new McpToolError(
            safeCode,
            "DML operation was not confirmed committed. Review the approval and audit outcome before retrying.",
            safeStage,
            retryable);
    }

    private static bool IsSafeCode(string? code) =>
        !string.IsNullOrWhiteSpace(code)
        && code.Length <= 100
        && code.All(c => c is >= 'a' and <= 'z' or >= '0' and <= '9' or '.' or '_' or '-');

    internal static McpToolError Classify(Exception error, McpErrorSurface surface)
    {
        ArgumentNullException.ThrowIfNull(error);
        for (Exception? current = error; current is not null; current = current.InnerException)
        {
            var evidence = SqlCompileEvidence.TryGetFromException(current);
            if (evidence is not null)
                return new McpToolError(
                    evidence.DecisionCode,
                    "SQL compilation was rejected. Review the diagnostic code and stage.",
                    evidence.DecisionBoundary.ToString());
        }

        if (error is UnauthorizedAccessException)
        {
            // Safe, application-owned exact messages keep useful distinctions.
            var message = error.Message switch
            {
                "MCP tool authorization context is missing." =>
                    "MCP tool authorization context is missing.",
                "MCP table authorization context is missing." =>
                    "MCP table authorization context is missing.",
                _ when error.Message.StartsWith("API key does not have permission", StringComparison.Ordinal) =>
                    "API key does not have permission to use this tool.",
                _ => "Access denied by MCP authorization policy."
            };
            return new McpToolError("authorization.denied", message, "Authorization");
        }

        if (error is TimeoutException)
            return surface == McpErrorSurface.Metadata
                ? new McpToolError("metadata.timeout", "Metadata request timed out.", "Metadata", true)
                : new McpToolError("execution.timeout", "Database operation timed out.", "Execution", true);

        if (error is InvalidOperationException
            && error.Message.StartsWith("Server busy:", StringComparison.Ordinal))
            return new McpToolError(
                "server.busy", "Server busy: maximum concurrent SQL operations reached.",
                surface == McpErrorSurface.Metadata ? "Metadata" : "Execution", true);

        if (surface == McpErrorSurface.Dml)
        {
            if (error is DmlCommitOutcomeUnknownException)
                return ForDmlOutcomeUnknown("dml.commit_outcome_unknown");
            if (error is DmlRollbackOutcomeUnknownException)
                return ForDmlOutcomeUnknown("dml.rollback_outcome_unknown");
            if (error is NotSupportedException)
                return new McpToolError(
                    "dml.unsupported_statement",
                    "Unsupported DML statement (including INSERT ... SELECT); fail-closed.",
                    "Capability");
            if (error is InvalidOperationException
                && error.Message.Contains("durable approval lifecycle", StringComparison.OrdinalIgnoreCase))
                return new McpToolError(
                    "approval.lifecycle_unavailable",
                    "DML approval lifecycle is unavailable. Check server diagnostics.",
                    "Approval");
            return new McpToolError(
                "dml.execution_failed", "DML operation failed. Review audit state before retrying.",
                "Execution");
        }

        if (surface == McpErrorSurface.Metadata)
            return new McpToolError(
                "metadata.failed", "Metadata operation failed. Check server diagnostics.", "Metadata");

        return new McpToolError(
            "execution.failed", "Query execution failed. Check server diagnostics.", "Execution");
    }
}
